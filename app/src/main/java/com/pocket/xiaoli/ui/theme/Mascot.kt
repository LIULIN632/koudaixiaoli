 * 没有名字就等于这一组控件对读屏用户不存在。
 */
data class MascotColor(val hex: String, val label: String)

/**
 * 可选配色。
 *
 * ⚠️ **刻意没有纯黑 `#000000`**（调研稿里有）：深色主题的背景是 `#1A1C1E`，
 * 纯黑的鱼压在上面只看得见两只眼睛，等于"用户选了个不存在的形象"。
 * 最深取 `#2B2F38`，在深色下仍能靠高光渐变读出体积。
 *
 * 选色是**本色**，渲染时顶部会往白里提 40%（见 `MascotAvatar`），
 * 所以这里不必为"哪个颜色更好看"操心立体感。
 */
