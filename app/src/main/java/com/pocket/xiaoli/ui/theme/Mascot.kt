/**
 * 当前形象 = 形状名 + 本色。
 *
 * 两个字段都是**存储值的原样**（名字而不是索引、色值而不是枚举）——
 * 用索引存的话，将来往 [MascotShapes.all] 中间插一个形状就会让所有老用户换脸，
 * 而在末尾追加则不会。名字是稳定的，索引不是。
 */
data class MascotLook(
    val shapeName: String = MascotShapes.defaultName,
    val colorHex: String = MascotPalette.DEFAULT,
) {
    /** 查表后的形状，渲染直接用它（名字不认识时这里已经退回默认）。 */
    val shape: MascotShape get() = MascotShapes.byName(shapeName)

    /** 解析后的本色。 */
    val color: Color get() = parseMascotColor(colorHex)
}

/**
 * 当前形象的分发通道。
 *
 * 在 `AppNavigation` 的 NavHost 外层 provide 一次，头像就地读 —— 理由与
 * `LocalProfileRowPadding` 完全一致：它要影响四个文件里的多处头像（对话气泡、
 * 空态欢迎页、「我的」徽标、设置页预览），中间隔着好几个页面；按参数一层层穿透
 * 会写出十几个函数签名。项目为 `onComposerFocusChange` 这么干过一次，
 * 后果是**只有那一个控件生效**。
 *
 * ## ⚠️ 这里用 `compositionLocalOf`，不是 `staticCompositionLocalOf`
 *
 * 行内边距那份用 static：它变化极少，且变了就该让整页重新量一遍。
 * 而形象是用户在设置页**每点一次形状就变一次**的 —— static 版会让**整棵内容子树**
 * 作废（一次全 App 重组）。动态版只让真正读了它的头像重组，代价是每处读一次
 * 一次哈希比较。两者的判据不同，不是前后不一致。
 *
 * 默认值是**默认形象**而不是"未设置"：快照测试单独渲某个头像时不 provide 也能出图，
 * 且出的就是老用户升级后看到的那条鱼。
 */
val LocalMascotLook = compositionLocalOf { MascotLook() }

/**
 * 解析 `#RRGGBB`。
 *
 * 刻意**不用 `android.graphics.Color.parseColor`**：那个函数对 `#RGB`、`#AARRGGBB`
 * 与颜色名都有分支，还会在非法输入上抛 `IllegalArgumentException` ——
 * 而这里的输入来自存储值，是**不可信**的（老版本写入 / 手改 prefs）。
 * 非法输入一律退回默认色，绝不抛。
 */
fun parseMascotColor(hex: String): Color {
    val body = hex.trim().removePrefix("#")
    if (body.length != 6) return MascotPalette.defaultColor
    val rgb = body.toLongOrNull(radix = 16) ?: return MascotPalette.defaultColor
    return Color(0xFF000000L or rgb)
}
