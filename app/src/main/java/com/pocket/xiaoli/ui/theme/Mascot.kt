/**
 * 鲤鱼的**吉祥物**：形状表 + 调色板 + 当前形象的通道。
 *
 * ## 为什么要自绘，而不是继续用 emoji
 *
 * 改造前头像是一个 `Text("🐟")`。emoji 的实际长相由**系统字体**决定：
 * 同一个包在 MIUI / 原生 / 各家 ROM 上画的不是同一条鱼，颜色、姿态、朝向都不受控 ——
 * 而它是这个 App 唯一有"角色"意味的元素。换成矢量之后，形状和配色都成了**数据**，
 * 于是"换装"这件事只是换两个字符串（见 [MascotLook]）。
 *
 * ## 坐标口径：**100 × 100 视口**
 *
 * [MascotShape.pathData] 与三个眼位字段都在同一个 100×100 的坐标系里，
 * 渲染时按目标尺寸等比换算（见 `MascotAvatar`）。这样新增物种只要抄一条 path 数据，
 * 不必关心它最终画多大。
 *
 * ## 数据从哪来
 *
 * 形状与色板取自 2026-10 那次「屁岱式吉祥物」调研的实现稿（`LOCALSEND` 里那四份文档）。
 * 唯一有意的偏离：**去掉了纯黑**，理由见 [MascotPalette]。
 */
/**
 * 一只眼睛：中心点、两个半轴与倾角，全部在 100×100 视口里。
 *
 * 从「所有形状共用一对 3.6×4.8、外斜 7° 的眼睛」升级成逐形状可配，是因为 2026-10
 * 加进来的 DS Bot 两个形象眼睛差着一倍（蓝鲸 9.3×23.0、它的右眼 7.0×22.9，倾角还各不同）——
 * 共用一套参数会把它们画成两只小豆眼。
 */
data class MascotEye(
    val x: Float,
    val y: Float,
    /** 水平半轴。 */
    val rx: Float = MascotShapes.EYE_RADIUS_X,
    /** 垂直半轴。眨眼时乘缩放系数。 */
    val ry: Float = MascotShapes.EYE_RADIUS_Y,
    /** 绕自身中心的倾角，正 = 顺时针。外斜让形象有表情，内斜会显得生气。 */
    val tilt: Float = 0f,
)

/**
 * 叠在身体上的一层纯色（阴影 / 高光 / 肚皮）。
 *
 * DS Bot 的吉祥物是「身体 + 肚皮 + 阴影 + 高光」三四层叠出来的立体感，单层渐变做不出来。
 * 层的顺序就是绘制顺序，与它的 SVG 一致；颜色与透明度取自 `logo.svg` 的
 * `fill` / `fill-opacity`（Apache-2.0，见 [MascotShapes] 的说明）。
 */
data class MascotLayer(val pathData: String, val argb: Long, val alpha: Float = 1f)

/** 白：高光与肚皮用。 */
private const val WHITE_ARGB = 0xFFFFFFFFL

/** 黑：阴影层用（透明度由 [MascotLayer.alpha] 给）。 */
private const val BLACK_ARGB = 0xFF000000L

/** 渐变上的一个停靠点：位置 0..1 + 颜色。 */
data class MascotStop(val offset: Float, val argb: Long)

/**
 * 形象**自带的配色**（DS Bot 那 7 个），照它源码里的底色 / 渐变来。
 *
 * 为 null 表示"用色盘里的本色" —— 6 条鱼走这条，所以用户换颜色时变的是它们。
 *
 * ⚠️ 自带配色的形象**不叠本色那层「顶部提亮 40%」**：DS Bot 的体积感来自
 * 它自己的阴影 / 高光层，再补一层提亮会把它画成塑料。
 */
data class MascotBody(
    val argb: Long,
    /** 非空时按这些停靠点画线性渐变（星星是三色渐变），[argb] 只作兜底。 */
    val gradient: List<MascotStop> = emptyList(),
    /** 渐变在 100×100 视口里的起止点，默认取 DS Bot 星星的 `userSpaceOnUse` 坐标。 */
    val x1: Float = 18f,
    val y1: Float = 10f,
    val x2: Float = 78f,
    val y2: Float = 92f,
)

/** 一个形象：一条主体 path + 一组眼睛 + 若干叠色层。全部在 100×100 视口里。 */
data class MascotShape(
    /** 展示名，同时也是**存储值**（`TabAppearance.assistantMascotShape` 存的就是它）。 */
    val name: String,
    /** 100×100 视口里的 path 数据：身体 + 鳍/尾，可含多条子路径。 */
    val pathData: String,
    /** 自带配色；**null = 用色盘里的本色**（6 条鱼）。 */
    val body: MascotBody? = null,
    /** 眼睛。顺序即绘制顺序，左眼在前。 */
    val eyes: List<MascotEye>,
    /** 叠在身体上的层，**按列表顺序绘制**（先肚皮后阴影，否则阴影会被肚皮盖掉）。 */
    val layers: List<MascotLayer> = emptyList(),
    /**
     * 眼睛用**路径**画（而不是 [eyes] 那样的椭圆）：Grok Ball 的 48 点眼环、
     * npface 的圆角方眼都装不进椭圆。非空时优先用它，[eyes] 留空。
     */
    val eyeLayers: List<MascotLayer> = emptyList(),
    /**
     * 眼睛**每一帧现算**（Grok Ball 的三个身体）：眼形由 [MascotFaces] 的 32 个表情决定，
     * 用 [MascotProjection] 投到 100 视口。非空时 [eyes] / [eyeLayers] 都不参与绘制。
     *
     * 与 [eyeLayers] 的区别是"眼形是否固定"：头盔只有一种眼，装进 [eyeLayers]；
     * 圆球能换 32 种眼神，所以只存身体轮廓，眼睛现算。
     */
    val projection: MascotProjection? = null,
)

