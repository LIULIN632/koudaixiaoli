package com.pocket.xiaoli.core.text

/**
 * 学号脱敏：**只保留末 4 位**，其余一律星号。
 *
 * ## 为什么放在共享层
 *
 * 同一个学号会同时出现在手机（「我的」身份卡、绑定页、今日校园…）和桌面（「我的」身份卡、
 * 报名表、宿舍信息）。**同一串数字被两种方式遮住，用户会怀疑自己看错了账号** —— 这是信任问题。
 * `CLAUDE.md` 也把「学号脱敏只有一份实现」列为红线，跨端更该只有一份。
 *
 * 2026-10 实测：Android 侧历史上曾有过 5 份实现 / 3 种规则；桌面端窗口版原本抄的是
 * 「前 3 + 后 2」（`202****89`），与手机的「末 4 位」（`*********6789`）**规则不同**。
 * 本文件是唯一真源。
 *
 * ## 边界行为（有单测盯着）
 *
 * - `null` / 空白 → `""`：不显示 `****`，因为那表示「有账号但看不全」，不能拿来表示「没有」
 * - 长度 ≤ 4 → `****`：宁可全遮，也不要把短号整段露出来
 */
fun maskStudentId(value: String?): String {
    val s = value.orEmpty().trim()
    return when {
        s.isEmpty() -> ""
        s.length <= 4 -> "****"
        else -> "*".repeat(s.length - 4) + s.takeLast(4)
    }
}
